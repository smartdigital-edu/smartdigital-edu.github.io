# Sends only the greeting text below to Microsoft's Edge text-to-speech service.
"""Record Cici's greeting (EN Ana / BM Yasmin) and save per-word start times (ms) for the speech bubble."""
import asyncio, json, sys, edge_tts
out_audio, out_js = sys.argv[1], sys.argv[2]
LINES = {
    'en': ('en-US-AnaNeural', '-4%', '+15Hz', "Hi!! My name is Cici! Welcome to Kiddora!! Ready to learn and play?! Let's go!!"),
    'ms': ('ms-MY-YasminNeural', '+2%', '+40Hz', "Hai! Nama saya Cici! Selamat datang ke Kiddora! Sedia untuk belajar dan bermain? Jom!"),
}
async def main():
    times = {}
    for lang, (voice, rate, pitch, text) in LINES.items():
        c = edge_tts.Communicate(text, voice, rate=rate, pitch=pitch, volume='+10%', boundary='WordBoundary')
        audio, words = bytearray(), []
        async for ch in c.stream():
            if ch['type'] == 'audio': audio += ch['data']
            elif ch['type'] == 'WordBoundary': words.append((round(ch['offset'] / 10000), ch['text']))
        open(f'{out_audio}/cici-hello-{lang}.mp3', 'wb').write(audio)
        times[lang] = [t for t, _ in words]
        print(lang, len(words), words)
    open(out_js, 'w').write('/** Generated by the Cici voice script: start time (ms) of each spoken word in cici-hello-<lang>.mp3. */\nexport default ' + json.dumps(times) + ';\n')
asyncio.run(main())
