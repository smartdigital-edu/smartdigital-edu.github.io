# Usage: pip install edge-tts && python scripts/cici-voice.py public/audio/kiddora src/apps/kiddora/cici-timings.js
# Sends only the lines below to Microsoft's Edge text-to-speech service.
"""Record Cici's lines (EN Ana / BM Yasmin) and save per-word start times (ms) for the speech bubble.

Writes public/audio/kiddora/cici-<clip>-<lang>.mp3 and a timings module: { <clip>: { <lang>: [ms, ...] } }.
"""
import asyncio, json, sys, edge_tts
out_audio, out_js = sys.argv[1], sys.argv[2]
VOICES = {'en': ('en-US-AnaNeural', '+6%', '+15Hz'), 'ms': ('ms-MY-YasminNeural', '+10%', '+40Hz')}
CLIPS = {
    # Greeting when the home screen opens.
    'hello': {
        'en': "Hi!! My name is Cici! Welcome to Kivokid!! Ready to learn and play?! Let's go!!",
        'ms': "Hai! Nama saya Cici! Selamat datang ke Kivokid! Sedia untuk belajar dan bermain? Jom!",
    },
    # When the child taps Cici after that.
    'tap': {
        'en': "Let's learn together!! Pick an activity to get started!!",
        'ms': "Jom belajar bersama! Pilih aktiviti untuk bermula!",
    },
}
async def main():
    times = {}
    for clip, langs in CLIPS.items():
        for lang, text in langs.items():
            voice, rate, pitch = VOICES[lang]
            c = edge_tts.Communicate(text, voice, rate=rate, pitch=pitch, volume='+10%', boundary='WordBoundary')
            audio, words = bytearray(), []
            async for ch in c.stream():
                if ch['type'] == 'audio': audio += ch['data']
                elif ch['type'] == 'WordBoundary': words.append((round(ch['offset'] / 10000), ch['text']))
            open(f'{out_audio}/cici-{clip}-{lang}.mp3', 'wb').write(audio)
            times.setdefault(clip, {})[lang] = [t for t, _ in words]
            print(clip, lang, len(words), [w for _, w in words])
    open(out_js, 'w').write('/** Generated by scripts/cici-voice.py: start time (ms) of each spoken word, per clip and language. */\nexport default ' + json.dumps(times) + ';\n')
asyncio.run(main())
