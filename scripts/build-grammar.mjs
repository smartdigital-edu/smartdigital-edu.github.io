/* ---------- validate + write ---------- */
let total = 0;
for (const [id, topic] of Object.entries(topics)) {
  topic.questions.forEach((q, i) => {
    q.id = `${id}-${String(i + 1).padStart(3, '0')}`;
    if (q.type === 'spot') {
      const words = q.sentence.split(' ').map((w) => w.replace(/[.,!?;:]+$/, '').toLowerCase());
      const hits = words.filter((w) => w === q.answer.toLowerCase()).length;
      if (hits !== 1) throw new Error(`${q.id}: "${q.answer}" appears ${hits} times in "${q.sentence}"`);
    }
    if ((q.type === 'fill' || q.type === 'mc') && new Set(q.options).size !== q.options.length) throw new Error(`${q.id}: duplicate options`);
    if (q.type === 'fill' && !q.sentence.includes('___')) throw new Error(`${q.id}: fill needs ___`);
  });
  if (topic.questions.length < 40) throw new Error(`${id} has only ${topic.questions.length} questions`);
  total += topic.questions.length;
  writeFileSync(`${OUT}/${id}.json`, `${JSON.stringify({ id, ...topic }, null, 2)}\n`);
  console.log(`${id.padEnd(16)} ${topic.questions.length} questions`);
}
console.log(`total: ${total}`);
