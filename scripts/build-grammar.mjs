/**
 * Authoring helper for Grammar Hub content.
 * The compact tables below are expanded into /src/content/grammarhub/<topic>.json.
 * You can edit those JSON files directly instead – the app only reads the JSON.
 * Run:  npm run content:grammar
 *
 * Question helpers (y = KSSR year 1–6):
 *   F(y, sentence-with-___, answer, [wrong options], explanation?)   fill in the blank
 *   M(y, prompt, sentence|null, answer, [wrong options], explanation?) multiple choice
 *   S(y, sentence, wrongWord, correction, explanation?)               spot the mistake
 *   W(y, word, hint, explanation?)                                    spelling (audio)
 *   Bd(y, sentence, explanation?)                                     build the sentence
 */
import { writeFileSync, mkdirSync } from 'node:fs';

const OUT = 'src/content/grammarhub';
mkdirSync(OUT, { recursive: true });

const F = (year, sentence, answer, wrong, explanation) => ({
  type: 'fill', year, prompt: 'Choose the correct word to complete the sentence.', sentence, options: [answer, ...wrong], answer,
  explanation: explanation || `The complete sentence is: "${sentence.replace(/\s*\(.*?\)\s*$/, '').replace('___', answer)}"`,
});
const M = (year, prompt, sentence, answer, wrong, explanation) => ({
  type: 'mc', year, prompt, ...(sentence ? { sentence } : {}), options: [answer, ...wrong], answer,
  explanation: explanation || `The correct answer is "${answer}".`,
});
const S = (year, sentence, answer, correction, explanation) => ({
  type: 'spot', year, prompt: 'Spot the mistake: tap the word that is wrong.', sentence, answer, correction,
  explanation: `"${answer}" should be "${correction}".${explanation ? ` ${explanation}` : ''}`,
});
const W = (year, word, hint, explanation) => ({
  type: 'spelling', year, word, hint, prompt: 'Listen and spell the word.',
  explanation: explanation || `${word} is spelt ${word.toUpperCase().split('').join('-')}.`,
});
const Bd = (year, answer, explanation) => ({
  type: 'build', year, answer, prompt: 'Put the words in the correct order to make a sentence.',
  explanation: explanation || 'A sentence starts with a capital letter, has a subject and a verb, and ends with a full stop, question mark or exclamation mark.',
});

